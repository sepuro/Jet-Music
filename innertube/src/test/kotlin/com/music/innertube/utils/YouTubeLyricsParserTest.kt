package com.music.innertube.utils

import com.music.innertube.models.response.PlayerResponse
import kotlinx.serialization.json.Json
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

class YouTubeLyricsParserTest {

  @Test
  fun extractsTimedLyricsDataIntoStandardLrc() {
    val browseJson =
      Json.parseToJsonElement(
        """
        {
          "contents": {
            "sectionListRenderer": {
              "contents": [
                {
                  "elementRenderer": {
                    "newElement": {
                      "type": {
                        "componentType": {
                          "model": {
                            "timedLyricsModel": {
                              "lyricsData": {
                                "timedLyricsData": [
                                  {
                                    "lyricLine": "First line",
                                    "cueRange": {
                                      "startTimeMilliseconds": "12340",
                                      "endTimeMilliseconds": "15000"
                                    }
                                  },
                                  {
                                    "lyricLine": "Second line",
                                    "cueRange": {
                                      "startTimeMilliseconds": "65090",
                                      "endTimeMilliseconds": "68000"
                                    }
                                  }
                                ]
                              }
                            }
                          }
                        }
                      }
                    }
                  }
                }
              ]
            }
          }
        }
        """.trimIndent()
      )

    val lrc = YouTubeLyricsParser.extractTimedLyricsFromBrowseJson(browseJson)
    assertEquals("[00:12.34]First line\n[01:05.09]Second line", lrc)
  }

  @Test
  fun selectsOnlyNonAutoGeneratedCaptionTracks() {
    val tracks =
      listOf(
        PlayerResponse.Captions.PlayerCaptionsTracklistRenderer.CaptionTrack(
          baseUrl = "https://www.youtube.com/api/timedtext?v=1&kind=asr",
          name = PlayerResponse.Captions.PlayerCaptionsTracklistRenderer.CaptionTrack.Name("English (auto-generated)"),
          vssId = "a.en",
          languageCode = "en",
          kind = "asr",
        ),
        PlayerResponse.Captions.PlayerCaptionsTracklistRenderer.CaptionTrack(
          baseUrl = "https://www.youtube.com/api/timedtext?v=1&lang=es",
          name = PlayerResponse.Captions.PlayerCaptionsTracklistRenderer.CaptionTrack.Name("Spanish"),
          vssId = ".es",
          languageCode = "es",
          kind = null,
        ),
      )

    val selected = YouTubeLyricsParser.selectManualCaptionTracks(tracks, preferredLanguage = "en-US")
    assertEquals(1, selected.size)
    assertEquals("es", selected.first().languageCode)
  }

  @Test
  fun returnsEmptyWhenOnlyAutoGeneratedCaptionsExist() {
    val tracks =
      listOf(
        PlayerResponse.Captions.PlayerCaptionsTracklistRenderer.CaptionTrack(
          baseUrl = "https://www.youtube.com/api/timedtext?v=1",
          vssId = "a.en",
          languageCode = "en",
          kind = "asr",
        )
      )

    val selected = YouTubeLyricsParser.selectManualCaptionTracks(tracks, preferredLanguage = "en")
    assertTrue(selected.isEmpty())
  }

  @Test
  fun parsesJson3AndSrv3CaptionsToLrc() {
    val json3 =
      """
      {
        "events": [
          { "tStartMs": 5120, "dDurationMs": 2000, "segs": [ { "utf8": "Hello " }, { "utf8": "world" } ] },
          { "tStartMs": 9000, "dDurationMs": 1000, "segs": [ { "utf8": "\n" } ] },
          { "tStartMs": 10500, "dDurationMs": 3000, "segs": [ { "utf8": "Line &amp; two" } ] }
        ]
      }
      """.trimIndent()

    assertEquals("[00:05.12]Hello world\n[00:10.50]Line & two", YouTubeLyricsParser.parseJson3ToLrc(json3))

    val srv3 =
      """
      <?xml version="1.0" encoding="utf-8" ?>
      <timedtext format="3">
        <body>
          <p t="5120" d="2000">Hello <s>world</s></p>
          <p t="10500" d="3000">Line &amp; two</p>
        </body>
      </timedtext>
      """.trimIndent()

    assertEquals("[00:05.12]Hello world\n[00:10.50]Line & two", YouTubeLyricsParser.parseSrv3ToLrc(srv3))
    assertNull(YouTubeLyricsParser.parseJson3ToLrc("not json"))
  }
}
